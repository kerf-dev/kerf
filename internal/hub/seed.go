package hub

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"strings"

	"github.com/kerf-dev/kerf/internal/hub/hubapi"
	"github.com/kerf-dev/kerf/internal/hub/store"
)

// DevSeedTokens reads the dev tokens: files in TokensDir (one per key) or the inline map.
// Keys are cluster names (agent tokens), "ui" and "admin".
func DevSeedTokens(d DevSeed) (map[string]string, error) {
	out := map[string]string{}
	for k, v := range d.Tokens {
		out[k] = strings.TrimSpace(v)
	}
	if d.TokensDir == "" {
		return out, nil
	}
	entries, err := os.ReadDir(d.TokensDir)
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		// Secret volumes contain ..data symlinks; take regular names only.
		if strings.HasPrefix(e.Name(), ".") || e.IsDir() {
			continue
		}
		b, err := os.ReadFile(filepath.Join(d.TokensDir, e.Name()))
		if err != nil {
			return nil, err
		}
		out[e.Name()] = strings.TrimSpace(string(b))
	}
	return out, nil
}

// RunDevSeed registers the dev clusters and stores the hashes of the dev tokens. Idempotent.
func RunDevSeed(ctx context.Context, st *store.Store, d DevSeed, log *slog.Logger) error {
	for _, c := range d.Clusters {
		if !hubapi.ClusterNameRE.MatchString(c) {
			return fmt.Errorf("devSeed: invalid cluster name %q", c)
		}
		if err := st.EnsureCluster(ctx, c, "registered by dev seed"); err != nil {
			return err
		}
	}
	tokens, err := DevSeedTokens(d)
	if err != nil {
		return err
	}
	for key, tok := range tokens {
		if tok == "" {
			continue
		}
		role, cluster := hubapi.RoleAgent, key
		switch key {
		case hubapi.RoleUI, hubapi.RoleAdmin, hubapi.RolePricing:
			role, cluster = key, ""
		default:
			if err := st.EnsureCluster(ctx, key, "registered by dev seed"); err != nil {
				return err
			}
		}
		if err := st.EnsureToken(ctx, tok, role, cluster, "dev seed: "+key); err != nil {
			return err
		}
	}
	log.InfoContext(ctx, "dev seed applied", "clusters", len(d.Clusters), "tokens", len(tokens))
	return nil
}

// Local token files in LocalTokens.Dir.
const (
	localTokenAgent   = "agent"
	localTokenPricing = "pricing"
)

// SeedLocalTokens stores the hashes of the tokens the chart generated for this release's pricing
// service and, with lt.Cluster, the agent of the hub's own cluster, and registers that cluster.
// Idempotent: a known token (also a revoked one) and a known cluster (also a deleted one) are
// left as they are. A missing or empty file is skipped.
func SeedLocalTokens(ctx context.Context, st *store.Store, lt LocalTokens, log *slog.Logger) error {
	if lt.Dir == "" {
		return nil
	}
	read := func(name string) (string, error) {
		b, err := os.ReadFile(filepath.Join(lt.Dir, name))
		if errors.Is(err, os.ErrNotExist) {
			return "", nil
		}
		if err != nil {
			return "", fmt.Errorf("localTokens: %w", err)
		}
		return strings.TrimSpace(string(b)), nil
	}
	pricingTok, err := read(localTokenPricing)
	if err != nil {
		return err
	}
	if pricingTok != "" {
		if err := st.EnsureToken(ctx, pricingTok, hubapi.RolePricing, "", "pricing service (generated by the chart)"); err != nil {
			return err
		}
	}
	agentTok := ""
	if lt.Cluster != "" {
		if !hubapi.ClusterNameRE.MatchString(lt.Cluster) {
			return fmt.Errorf("localTokens.cluster: invalid cluster name %q", lt.Cluster)
		}
		if agentTok, err = read(localTokenAgent); err != nil {
			return err
		}
		if agentTok != "" {
			if err := st.EnsureCluster(ctx, lt.Cluster, "the hub's own cluster (global.mode all)"); err != nil {
				return err
			}
			if err := st.EnsureToken(ctx, agentTok, hubapi.RoleAgent, lt.Cluster, "agent of "+lt.Cluster+" (generated by the chart)"); err != nil {
				return err
			}
		}
	}
	log.InfoContext(ctx, "local tokens applied", "pricing", pricingTok != "", "agent", agentTok != "", "cluster", lt.Cluster)
	return nil
}
