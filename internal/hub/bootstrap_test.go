// A generated bootstrap password must be changed at first sign-in; one the operator chose is not forced.
func TestBootstrapAdminMustChangePassword(t *testing.T) {
	for _, tc := range []struct {
		name      string
		generated bool
	}{
		{"generated by the chart", true},
		{"chosen by the operator", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			e := newEnv(t)
			pwFile := filepath.Join(t.TempDir(), "password")
			if err := os.WriteFile(pwFile, []byte("first password here\n"), 0o600); err != nil {
				t.Fatal(err)
			}
			cfg := e.srv.Cfg
			cfg.Auth.BootstrapAdmin = BootstrapAdmin{Username: "admin", PasswordFile: pwFile, MustChangePassword: tc.generated}
			if err := BootstrapUsers(e.ctx, e.st, cfg, discardLog()); err != nil {
				t.Fatal(err)
			}
			s, me := e.login("admin", "first password here")
			if me.User == nil || me.User.MustChangePassword != tc.generated {
				t.Fatalf("login: mustChangePassword = %+v, want %v", me.User, tc.generated)
			}
			if !tc.generated {
				return
			}
			// Changing it clears the flag.
			r := e.sdo(s, http.MethodPost, "/v1/me/password", hubapi.PasswordChange{CurrentPassword: "first password here", NewPassword: "a password I chose"})
			if r.code != http.StatusNoContent {
				t.Fatalf("change password: %d %s", r.code, r.body)
			}
			if _, me := e.login("admin", "a password I chose"); me.User == nil || me.User.MustChangePassword {
				t.Errorf("after the change: mustChangePassword = %+v", me.User)
			}
		})
	}
}

// The chart's local tokens are accepted after SeedLocalTokens; seeding twice changes nothing, and a
// revoked token stays revoked.
func TestSeedLocalTokens(t *testing.T) {
	const agentTok, pricingTok = "local-agent-token-0123456789", "local-pricing-token-0123456789"
	for _, tc := range []struct {
		name      string
		cluster   string
		files     map[string]string
		wantAgent bool
		wantPrice bool
		wantErr   bool
	}{
		{name: "mode all", cluster: "lab", files: map[string]string{"agent": agentTok + "\n", "pricing": pricingTok}, wantAgent: true, wantPrice: true},
		{name: "mode hub: no cluster, agent file ignored", files: map[string]string{"agent": agentTok, "pricing": pricingTok}, wantPrice: true},
		{name: "missing and empty files are skipped", cluster: "lab", files: map[string]string{"pricing": "  \n"}},
		{name: "invalid cluster name", cluster: "Not_A_Label", files: map[string]string{"agent": agentTok}, wantErr: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			st := newTestStore(t, "")
			ctx := t.Context()
			dir := t.TempDir()
			for name, v := range tc.files {
				if err := os.WriteFile(filepath.Join(dir, name), []byte(v), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			lt := LocalTokens{Dir: dir, Cluster: tc.cluster}
			for i := 0; i < 2; i++ { // idempotent
				err := SeedLocalTokens(ctx, st, lt, discardLog())
				if tc.wantErr {
					if err == nil {
						t.Fatal("want an error")
					}
					return
				}
				if err != nil {
					t.Fatal(err)
				}
			}
			check := func(tok, role, cluster string, want bool) {
				t.Helper()
				p, err := st.LookupToken(ctx, tok)
				if !want {
					if err == nil {
						t.Errorf("token of role %s accepted, want unknown", role)
					}
					return
				}
				if err != nil {
					t.Fatalf("token of role %s: %v", role, err)
				}
				if p.Role != role || p.Cluster != cluster {
					t.Errorf("token: role %q cluster %q, want %q %q", p.Role, p.Cluster, role, cluster)
				}
			}
			check(agentTok, hubapi.RoleAgent, tc.cluster, tc.wantAgent)
			check(pricingTok, hubapi.RolePricing, "", tc.wantPrice)
			clusters, err := st.Clusters(ctx)
			if err != nil {
				t.Fatal(err)
			}
			if registered := len(clusters) == 1 && clusters[0].Name == tc.cluster; registered != tc.wantAgent {
				t.Errorf("clusters %+v, want %q registered: %v", clusters, tc.cluster, tc.wantAgent)
			}
			if !tc.wantPrice {
				return
			}
			// A revoked token is not brought back by the next start.
			if _, err := st.Pool.Exec(ctx, `UPDATE api_tokens SET revoked_at = now() WHERE token_sha256 = $1`, store.HashToken(pricingTok)); err != nil {
				t.Fatal(err)
			}
			if err := SeedLocalTokens(ctx, st, lt, discardLog()); err != nil {
				t.Fatal(err)
			}
			check(pricingTok, hubapi.RolePricing, "", false)
		})
	}
}
